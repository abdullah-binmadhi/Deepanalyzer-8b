class ASTSecurityViolation(PermissionError):
    """Raised when incoming code violates the AST security boundary."""
    pass


class ASTFirewallVisitor(ast.NodeVisitor):
    """AST visitor that detects forbidden module imports, function calls, and attribute access."""

    FORBIDDEN_MODULES: Set[str] = {
        "socket", "requests", "urllib", "httpx", "aiohttp", "paramiko",
        "ftplib", "telnetlib", "smtplib", "poplib", "imaplib", "http",
        "subprocess", "shutil", "posix", "pty", "commands"
    }

    FORBIDDEN_CALLS: Set[str] = {
        "eval", "exec", "compile", "__import__", "open", "getattr", "setattr", "delattr"
    }

    FORBIDDEN_OS_ATTRS: Set[str] = {
        "system", "popen", "spawn", "fork", "kill", "remove", "unlink",
        "rmdir", "removedirs", "chmod", "chown", "truncate", "environ", "getenv"
    }

    FORBIDDEN_DUNDERS: Set[str] = {
        "__subclasses__", "__globals__", "__code__", "__builtins__", "__dict__", "__class__"
    }

    def __init__(self):
        super().__init__()
        self.violations: List[str] = []

    def visit_Import(self, node: ast.Import) -> None:
        for alias in node.names:
            root_module = alias.name.split(".")[0]
            if root_module in self.FORBIDDEN_MODULES:
                self.violations.append(f"Forbidden module import: `{alias.name}`")
        self.generic_visit(node)

    def visit_ImportFrom(self, node: ast.ImportFrom) -> None:
        if node.module:
            root_module = node.module.split(".")[0]
            if root_module in self.FORBIDDEN_MODULES:
                self.violations.append(f"Forbidden from-import: `{node.module}`")
            if root_module == "os":
                for alias in node.names:
                    if alias.name in self.FORBIDDEN_OS_ATTRS:
                        self.violations.append(f"Forbidden os attribute import: `os.{alias.name}`")
        self.generic_visit(node)

    def visit_Call(self, node: ast.Call) -> None:
        if isinstance(node.func, ast.Name):
            if node.func.id in self.FORBIDDEN_CALLS:
                self.violations.append(f"Forbidden direct function call: `{node.func.id}()`")

        elif isinstance(node.func, ast.Attribute):
            attr_name = node.func.attr
            if attr_name in self.FORBIDDEN_DUNDERS:
                self.violations.append(f"Forbidden dunder attribute invocation: `.{attr_name}`")
            if isinstance(node.func.value, ast.Name) and node.func.value.id == "os":
                if attr_name in self.FORBIDDEN_OS_ATTRS:
                    self.violations.append(f"Forbidden OS call: `os.{attr_name}()`")

        self.generic_visit(node)

    def visit_Attribute(self, node: ast.Attribute) -> None:
        if node.attr in self.FORBIDDEN_DUNDERS:
            self.violations.append(f"Forbidden dunder reflection: `.{node.attr}`")
        if isinstance(node.value, ast.Name) and node.value.id == "os":
            if node.attr in self.FORBIDDEN_OS_ATTRS:
                self.violations.append(f"Forbidden OS attribute access: `os.{node.attr}`")
        self.generic_visit(node)


def audit_code(code_str: str) -> bool:
    """Performs pre-execution static AST analysis.

    Raises ASTSecurityViolation if any forbidden patterns are discovered.
    """
    if not code_str or not code_str.strip():
        return True

    try:
        tree = ast.parse(code_str)
    except SyntaxError as err:
        raise SyntaxError(f"AST Parse Error in script: {err}")

    visitor = ASTFirewallVisitor()
    visitor.visit(tree)

    if visitor.violations:
        violation_summary = "\n- " + "\n- ".join(visitor.violations)
        raise ASTSecurityViolation(
            f"AST Security Violation Detected! The incoming code was blocked:\n{violation_summary}"
        )

    return True


