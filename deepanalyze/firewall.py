def create_pipeline_file(dataset_dir: str, file_type: str = "py") -> str:
    """Creates an empty clean_pipeline.py or clean_pipeline.ipynb in the dataset directory."""
    os.makedirs(dataset_dir, exist_ok=True)
    if file_type.lower() in ("ipynb", "notebook", "2"):
        file_path = os.path.join(dataset_dir, "clean_pipeline.ipynb")
        notebook_content = {
            "cells": [
                {
                    "cell_type": "markdown",
                    "metadata": {},
                    "source": [
                        "# DeepAnalyze Data Transformation Pipeline\n",
                        "Generated by DeepAnalyze v4.0 Air-Gap Gateway."
                    ]
                }
            ],
            "metadata": {
                "language_info": {
                    "name": "python",
                    "version": "3.11"
                }
            },
            "nbformat": 4,
            "nbformat_minor": 5
        }
        with open(file_path, "w", encoding="utf-8") as f:
            json.dump(notebook_content, f, indent=1)
        return file_path
    else:
        file_path = os.path.join(dataset_dir, "clean_pipeline.py")
        header = (
            "# DeepAnalyze Data Transformation Pipeline\n"
            "# Generated by DeepAnalyze v4.0 Air-Gap Gateway\n"
            "import pandas as pd\n"
            "import numpy as np\n"
            "import polars as pl\n\n"
        )
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(header)
        return file_path


def append_code_to_pipeline(file_path: str, code_block: str) -> None:
    """Appends code block to clean_pipeline.py or as a new code cell to clean_pipeline.ipynb."""
    if not os.path.exists(file_path):
        return

    clean_code = code_block.strip()
    if not clean_code:
        return

    if file_path.endswith(".ipynb"):
        try:
            with open(file_path, "r", encoding="utf-8") as f:
                nb = json.load(f)

            source_lines = [line + "\n" for line in clean_code.splitlines()]
            new_cell = {
                "cell_type": "code",
                "execution_count": len(nb.get("cells", [])) + 1,
                "metadata": {},
                "outputs": [],
                "source": source_lines
            }
            nb.setdefault("cells", []).append(new_cell)

            with open(file_path, "w", encoding="utf-8") as f:
                json.dump(nb, f, indent=1)
        except Exception:
            pass
    else:
        with open(file_path, "a", encoding="utf-8") as f:
            f.write(f"\n# --- Pipeline Block ---\n{clean_code}\n")


