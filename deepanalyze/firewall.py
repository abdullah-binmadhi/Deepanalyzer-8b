def prepare_dataframe_for_code(df: Any, code_str: str) -> Tuple[Any, str]:
    """Auto-converts DataFrame between Pandas and Polars based on code dialect."""
    if df is None:
        return None, "none"

    code_lower = code_str.lower()
    has_polars_markers = any(k in code_lower for k in [
        "pl.", "polars", "with_columns", "pl.col", ".filter(pl.", ".select(pl."
    ])
    has_pandas_markers = any(k in code_lower for k in [
        "pd.", "pandas", "np.", "numpy", ".iloc", ".loc", ".apply(",
        ".ffill(", ".bfill(", ".reset_index(", "axis=", ".dropna(", ".fillna(",
        ".groupby(", ".drop(columns=", ".to_datetime("
    ]) or ("[" in code_str and "]" in code_str and not has_polars_markers)

    if has_pandas_markers and not has_polars_markers:
        if hasattr(df, "to_pandas"):
            try:
                return df.to_pandas(), "pandas"
            except Exception:
                pass
        return df, "pandas"
    elif has_polars_markers:
        if hasattr(df, "to_dict") and not isinstance(df, pl.DataFrame):
            try:
                return pl.from_pandas(df), "polars"
            except Exception:
                pass
        return df, "polars"
    else:
        # If code uses standard Pandas dataframe operations, default to pandas if already pandas
        return df, "pandas" if hasattr(df, "iloc") else "polars"


def execute_code_safely(
    code_str: str,
    global_scope: Dict[str, Any],
    timeout_sec: float = 15.0
) -> Dict[str, Any]:
    """Audits code and executes it within local RAM with a watchdog timer.

    Pre-injects pandas (pd), numpy (np), and polars (pl) to guarantee compatibility
    with external AI-generated transformation pipelines. Sets __name__ to '__main__'
    so script-style execution blocks execute naturally.
    """
    audit_code(code_str)

    # Set __name__ to __main__ so cloud AI 'if __name__ == "__main__":' blocks execute
    global_scope.setdefault("__name__", "__main__")

    # Pre-inject core data science and utility libraries expected by cloud AI code
    global_scope.setdefault("copy", copy)
    import re
    global_scope.setdefault("re", re)
    global_scope.setdefault("pl", pl)
    try:
        import pandas as pd
        global_scope.setdefault("pd", pd)
    except ImportError:
        pass
    try:
        import numpy as np
        global_scope.setdefault("np", np)
    except ImportError:
        pass

    exec_exception = None
    exec_completed = False

    def _target():
        nonlocal exec_exception, exec_completed
        try:
            exec(code_str, global_scope)
            exec_completed = True
        except Exception as e:
            exec_exception = e

    worker = threading.Thread(target=_target, daemon=True)
    worker.start()
    worker.join(timeout=timeout_sec)

    if worker.is_alive():
        raise TimeoutError(
            f"Script execution aborted: Execution exceeded watchdog timeout of {timeout_sec} seconds."
        )

    if exec_exception:
        raise exec_exception

    return global_scope


def resolve_transformed_dataframe(
    global_scope: Dict[str, Any],
    original_df: Any,
    primary_var: str = "df",
    input_path: Optional[str] = None
) -> Tuple[Any, str]:
    """Inspects execution scope, created files, and defined functions to harvest the transformed DataFrame.

    Handles:
    1. Output files created/modified on disk (OUTPUT_FILE, output_path, etc.)
    2. Explicitly assigned DataFrame variables (cleaned_df, df_clean, final_df, df, etc.)
    3. In-place modified DataFrames
    4. Callable pipeline functions (clean_*, transform_*, process_*, etc.)
    """
    import inspect
    try:
        import pandas as pd
    except ImportError:
        pd = None

    # 1. Check if output file was written to disk
    for key in ["OUTPUT_FILE", "output_path", "output_file", "clean_out_path", "OUTPUT_PATH"]:
        out_path = global_scope.get(key)
        if out_path and isinstance(out_path, str) and os.path.isfile(out_path) and pd is not None:
            try:
                if out_path.endswith(".csv"):
                    return pd.read_csv(out_path), f"output file `{os.path.basename(out_path)}`"
                elif out_path.endswith((".xlsx", ".xls")):
                    return pd.read_excel(out_path), f"output file `{os.path.basename(out_path)}`"
                elif out_path.endswith(".parquet"):
                    return pd.read_parquet(out_path), f"output file `{os.path.basename(out_path)}`"
            except Exception:
                pass

    # 2. Check candidate DataFrame variables in scope
    candidate_vars = [
        "df_cleaned", "cleaned_df", "df_clean", "clean_df", "final_df",
        "df_transformed", "transformed_df", "result_df", "result",
        "df_out", "out_df", "data_clean", "cleaned_data",
        "df", primary_var, "data"
    ]
    for var in candidate_vars:
        if var in global_scope:
            val = global_scope[var]
            if (pd is not None and isinstance(val, pd.DataFrame)) or isinstance(val, pl.DataFrame):
                if val is not original_df:
                    return val, f"variable `{var}`"
                if hasattr(val, "shape") and hasattr(original_df, "shape"):
                    if val.shape != original_df.shape:
                        return val, f"in-place modified `{var}`"
            elif isinstance(val, dict):
                # Handle multi-sheet dicts returned e.g. from pd.read_excel(..., sheet_name=None)
                if primary_var in val and ((pd is not None and isinstance(val[primary_var], pd.DataFrame)) or isinstance(val[primary_var], pl.DataFrame)):
                    return val[primary_var], f"sheet `{primary_var}` from dict `{var}`"
                for s_key, s_df in val.items():
                    if (pd is not None and isinstance(s_df, pd.DataFrame)) or isinstance(s_df, pl.DataFrame):
                        return s_df, f"sheet `{s_key}` from dict `{var}`"

    # 3. Check for callable transformation functions defined in scope
    for name, obj in list(global_scope.items()):
        if callable(obj) and not inspect.isclass(obj):
            lname = name.lower()
            if any(term in lname for term in ["clean", "transform", "process", "normalize", "unpivot", "flatten", "pipeline"]):
                try:
                    sig = inspect.signature(obj)
                    params = list(sig.parameters.values())
                    if params:
                        first_param = params[0].name.lower()
                        if any(p in first_param for p in ["path", "file", "csv", "xlsx", "input"]):
                            if input_path and os.path.isfile(input_path):
                                res = obj(input_path)
                                if (pd is not None and isinstance(res, pd.DataFrame)) or isinstance(res, pl.DataFrame):
                                    return res, f"function `{name}(input_path)`"
                        else:
                            res = obj(original_df)
                            if (pd is not None and isinstance(res, pd.DataFrame)) or isinstance(res, pl.DataFrame):
                                return res, f"function `{name}(df)`"
                except Exception:
                    pass

    return original_df, "unmodified original"


def audit_transformation_safety(
    raw_df: Any,
    transformed_df: Any,
    arch_key: str = "CLEAN_TABULAR",
    strict: bool = True
) -> Tuple[bool, str]:
    """Audits transformation results against the raw dataset for catastrophic data loss,

    destructive over-filtering, and financial/volumetric conservation breaches.
    Works dynamically and agnostically across all dataset architectures.
    """
    if raw_df is None or transformed_df is None:
        return True, "Null dataset bypassed safety audit."

    try:
        import pandas as pd
    except ImportError:
        pd = None

    # 1. Zero-Row / Empty DataFrame Fatal Check
    transformed_rows = transformed_df.height if hasattr(transformed_df, "height") else (
        transformed_df.shape[0] if hasattr(transformed_df, "shape") else len(transformed_df)
    )
    raw_rows = raw_df.height if hasattr(raw_df, "height") else (
        raw_df.shape[0] if hasattr(raw_df, "shape") else len(raw_df)
    )

    if raw_rows > 0 and transformed_rows == 0:
        raise OverCleaningViolation(
            "Over-Cleaning Fatal Error: Transformed DataFrame is completely empty (0 rows)! "
            "The transformation script discarded 100% of records."
        )

    # If raw dataset is small (<= 5 rows), bypass retention ratio check
    if raw_rows <= 5:
        return True, "Small dataset passed safety audit."

    # 2. Volumetric Retention & Over-Filtering Analysis
    retention_ratio = transformed_rows / raw_rows

    if arch_key == "ERP_RAGGED":
        expected_line_items = None
        try:
            from .erp_cleaner import sniff_erp_layout
            schema = sniff_erp_layout(raw_df)
            pdf = raw_df.to_pandas() if hasattr(raw_df, "to_pandas") else raw_df
            seq_count = 0
            if 0 <= schema.doc_col < pdf.shape[1]:
                series = pdf.iloc[:, schema.doc_col].dropna().astype(str).str.strip()
                for v in series:
                    try:
                        val_num = float(v)
                        if val_num >= 1000 or (val_num.is_integer() and 1 <= val_num <= 5000):
                            seq_count += 1
                    except ValueError:
                        pass
            if seq_count >= 5:
                expected_line_items = seq_count
        except Exception:
            pass

        if expected_line_items is not None and expected_line_items > 0:
            line_retention = transformed_rows / expected_line_items
            if line_retention < 0.4:
                raise OverCleaningViolation(
                    f"Over-Cleaning Violation: Transformed dataset retained only {transformed_rows} rows out of "
                    f"~{expected_line_items} expected line items ({line_retention*100:.1f}% line retention). "
                    f"Blind dropna() or destructive over-filtering detected in hierarchical ERP dataset."
                )
        else:
            if retention_ratio < 0.08 and transformed_rows < 15:
                raise OverCleaningViolation(
                    f"Over-Cleaning Violation: Transformed dataset retained only {transformed_rows} rows out of "
                    f"{raw_rows} raw rows ({retention_ratio*100:.1f}% retention). "
                    f"Severe record loss detected in hierarchical dataset."
                )

    else:
        # Standard tabular / relational dataset:
        if strict and retention_ratio < 0.70:
            loss_pct = (1.0 - retention_ratio) * 100
            raise OverCleaningViolation(
                f"Over-Cleaning Warning: Transformed dataset lost {loss_pct:.1f}% of records "
                f"({transformed_rows} rows remaining from {raw_rows} original rows). "
                f"Verify if blind dropna() or excessive deduplication was executed."
            )

    # 3. Numeric & Financial Conservation Check
    if pd is not None:
        try:
            raw_pdf = raw_df.to_pandas() if hasattr(raw_df, "to_pandas") else raw_df
            tx_pdf = transformed_df.to_pandas() if hasattr(transformed_df, "to_pandas") else transformed_df

            money_keywords = ["amount", "total", "price", "net", "gross", "debit", "credit", "balance", "cost", "sum"]
            raw_num_cols = [c for c in raw_pdf.columns if any(k in str(c).lower() for k in money_keywords)]
            tx_num_cols = [c for c in tx_pdf.columns if any(k in str(c).lower() for k in money_keywords)]

            if raw_num_cols and tx_num_cols:
                raw_sums = []
                for c in raw_num_cols:
                    clean_s = raw_pdf[c].astype(str).str.replace(",", "", regex=False).str.replace("$", "", regex=False).str.replace("₹", "", regex=False)
                    nums = pd.to_numeric(clean_s, errors="coerce").dropna()
                    if len(nums) > 0 and nums.sum() > 0:
                        raw_sums.append(nums.sum())

                tx_sums = []
                for c in tx_num_cols:
                    clean_s = tx_pdf[c].astype(str).str.replace(",", "", regex=False).str.replace("$", "", regex=False).str.replace("₹", "", regex=False)
                    nums = pd.to_numeric(clean_s, errors="coerce").dropna()
                    if len(nums) > 0:
                        tx_sums.append(nums.sum())

                if raw_sums:
                    max_raw = max(raw_sums)
                    max_tx = max(tx_sums) if tx_sums else 0.0
                    if max_raw > 100.0 and max_tx <= 0.0:
                        raise OverCleaningViolation(
                            f"Financial Conservation Violation: Raw dataset had substantial quantitative volume (sum ~{max_raw:,.2f}) "
                            f"but transformed dataset sum is 0.00. Quantitative columns were corrupted or zeroed out."
                        )
        except Exception as e:
            if isinstance(e, OverCleaningViolation):
                raise

    return True, f"Volumetric & retention safety verified ({transformed_rows:,} rows retained from {raw_rows:,})."


