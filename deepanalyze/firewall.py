class RollbackManager:
    """Manages an in-memory LIFO snapshot stack (up to 5 levels) for zero-latency undo."""

    def __init__(self, max_depth: int = 5):
        self.max_depth = max_depth
        self._stacks: Dict[str, List[Any]] = defaultdict(list)

    def push(self, target_name: str, df: Any) -> None:
        """Pushes a clone/copy of the DataFrame (Polars or Pandas) onto the rollback stack."""
        stack = self._stacks[target_name]
        if len(stack) >= self.max_depth:
            stack.pop(0)

        if hasattr(df, "clone"):
            snapshot = df.clone()
        elif hasattr(df, "copy"):
            snapshot = df.copy(deep=True)
        else:
            snapshot = copy.deepcopy(df)

        stack.append(snapshot)

    def pop(self, target_name: str) -> Optional[pl.DataFrame]:
        """Pops and returns the most recent DataFrame snapshot, or None if empty."""
        stack = self._stacks[target_name]
        if stack:
            return stack.pop()
        return None

    def clear(self, target_name: Optional[str] = None) -> None:
        if target_name:
            self._stacks[target_name].clear()
        else:
            self._stacks.clear()

    def depth(self, target_name: str) -> int:
        return len(self._stacks[target_name])


_GLOBAL_ROLLBACK = RollbackManager(max_depth=5)


def push_snapshot(target_name: str, df: pl.DataFrame) -> None:
    _GLOBAL_ROLLBACK.push(target_name, df)


def pop_snapshot(target_name: str) -> Optional[pl.DataFrame]:
    return _GLOBAL_ROLLBACK.pop(target_name)


def get_snapshot_depth(target_name: str) -> int:
    return _GLOBAL_ROLLBACK.depth(target_name)
