def write_pipeline_test_file(
    output_dir: str,
    input_file: str,
    output_file: str,
    pipeline_script: str,
    clean_df: Optional[Any] = None,
    filename: str = "test_clean_pipeline.py"
) -> str:
    """Writes the generated pytest test suite to disk."""
    test_code = generate_pipeline_test_code(input_file, output_file, pipeline_script, clean_df)
    target_path = os.path.join(output_dir, filename)
    with open(target_path, "w", encoding="utf-8") as f:
        f.write(test_code)
