def test_pipeline_execution():
    """Executes the transformation pipeline script via subprocess and validates exit code 0."""
    result = subprocess.run(
        [sys.executable, PIPELINE_PATH],
        capture_output=True,
        text=True,
        timeout=60
    )
    assert result.returncode == 0, f"Pipeline execution failed:\\n{{result.stderr}}"
    assert os.path.exists(OUTPUT_PATH), f"Output file was not created at {{OUTPUT_PATH}}"


