def test_detect_date_formats():
    samples_iso = ["2025-01-15", "2025-02-20", "2025-03-01"]
    fmts = detect_date_formats(samples_iso)
    assert any("YYYY-MM-DD" in f for f in fmts)

    samples_mixed = ["15/08/2025", "2025-08-15", "15-Aug-2025", "August 15, 2025"]
    mixed_fmts = detect_date_formats(samples_mixed)
    assert len(mixed_fmts) >= 3


def test_detect_accounting_negatives():
    samples_with_neg = ["1,250.00", "(500.00)", "75.50", "(SAR 1,000.00)"]
    assert detect_accounting_negatives(samples_with_neg) is True

    samples_trailing_minus = ["100.00", "250.00-", "50.00"]
    assert detect_accounting_negatives(samples_trailing_minus) is True

    clean_samples = ["1,250.00", "-500.00", "75.50"]
    assert detect_accounting_negatives(clean_samples) is False


def test_detect_dirty_currency():
    samples_curr = ["$100.50", "€45.00", "SAR 250", "£12.99"]
    assert detect_dirty_currency(samples_curr) is True

    clean_numbers = ["100.50", "45.00", "250", "12.99"]
    assert detect_dirty_currency(clean_numbers) is False


def test_detect_whitespace_issues():
    samples_ws = [" Riyadh", "Jeddah ", "Dammam\t", "Khobar\u00a0"]
    assert detect_whitespace_issues(samples_ws) is True

    clean_samples = ["Riyadh", "Jeddah", "Dammam", "Khobar"]
    assert detect_whitespace_issues(clean_samples) is False


def test_infer_column_role():
    assert infer_column_role("id", 1.0, "Int64", 0.0, ["1", "2", "3"]) == "Primary Key Candidate"
    assert infer_column_role("customer_age", 0.05, "Int64", 0.0, ["25", "30"]) == "Quasi-Identifier"
    assert infer_column_role("dept_code", 0.02, "String", 0.0, ["D1", "D2"]) == "Business Key / Foreign Identifier"
    assert infer_column_role("sales_amount", 0.8, "Float64", 0.0, ["100.5", "200.0"]) == "Numeric Metric / Quantitative"
    assert infer_column_role(
        "clinical_notes", 0.9, "String", 0.0,
        ["Patient presented with high fever and reported shortness of breath."]
    ) == "Free-Text Narrative / Clinical Note"


def test_profile_dataframe():
    df = pl.DataFrame({
        "tx_id": ["T1", "T2", "T3", "T4"],
        "date_str": ["2025-01-01", "15/02/2025", "2025-03-01", "10-Apr-2025"],
        "balance": ["1,000.00", "(250.00)", "$500.00", " SAR 300 "],
        "category": ["A", "B", "A", "B"],
    })

    profile = profile_dataframe(df, name="test_sheet")
    assert profile.sheet_name == "test_sheet"
    assert profile.row_count == 4
    assert profile.col_count == 4
    assert profile.role in (SheetRole.TRANSACTION_LEDGER, SheetRole.LOOKUP_DIMENSION)

    col_map = {c.name: c for c in profile.columns}
    assert col_map["balance"].has_accounting_negatives is True
    assert col_map["balance"].has_dirty_currency is True
    assert col_map["balance"].has_whitespace_issues is True
    assert len(col_map["date_str"].date_formats) >= 2


