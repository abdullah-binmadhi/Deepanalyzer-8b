def test_detect_foreign_keys():
    df1 = pl.DataFrame({
        "order_id": [1, 2, 3, 4],
        "cust_id": ["C100", "C101", "C102", "C103"],
        "amount": [50.0, 60.0, 70.0, 80.0],
    })
    df2 = pl.DataFrame({
        "cust_id": ["C100", "C101", "C102", "C104"],
        "cust_name": ["Alpha", "Beta", "Gamma", "Delta"],
    })

    p1 = profile_dataframe(df1, name="Orders")
    p2 = profile_dataframe(df2, name="Customers")

    candidates = detect_foreign_keys({"Orders": p1, "Customers": p2})
    assert len(candidates) >= 1
    fk = candidates[0]
    assert fk.from_col == "cust_id"
    assert fk.to_col == "cust_id"
    assert fk.overlap_pct >= 75.0


def test_generate_engineering_briefing():
    df1 = pl.DataFrame({
        "order_id": [1, 2, 3],
        "cust_id": ["C1", "C2", "C3"],
        "amount": ["$100.00", "(50.00)", " SAR 200 "],
        "date": ["2025-01-01", "02/02/2025", "15-Mar-2025"],
    })
    p1 = profile_dataframe(df1, name="Orders")

    topology = WorkbookTopology(
        file_path="mock_orders.xlsx",
        sheets={"Orders": p1},
        primary_sheet="Orders",
        foreign_keys=[],
        recommended_pipeline_steps=["Clean dirty currency and accounting negatives in `amount`."]
    )

    briefing = generate_engineering_briefing(topology, user_prompt="Consolidate and clean sales ledger")
    assert "AUTONOMOUS DATA ENGINEERING & TOPOLOGY BRIEFING" in briefing
    assert "Orders" in briefing
    assert "Mixed date formats" in briefing
    assert "accounting negative brackets" in briefing
    assert "Clean dirty currency" in briefing
